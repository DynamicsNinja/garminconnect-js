/** A category that has at least one named exercise — every key of {@link EXERCISES}. */
export type ExerciseCategoryWithNames = keyof typeof EXERCISES;

/** The exercise names valid for one category. */
export type ExerciseName<C extends ExerciseCategoryWithNames> = (typeof EXERCISES)[C][number];

/**
 * A `{ category, name }` pair, checked at compile time.
 *
 * Pass the result straight to a builder step's `exercise` option. At runtime this is the identity
 * function — all the work happens in the type system, so it costs nothing:
 *
 * ```ts
 * .interval({ reps: 10, exercise: exercise("BENCH_PRESS", "BARBELL_BENCH_PRESS") })
 * ```
 */
export function exercise<C extends ExerciseCategoryWithNames, N extends ExerciseName<C>>(
  category: C,
  name: N,
): { category: C; name: N } {
  return { category, name };
}

/**
 * Whether `name` is a valid exercise for `category`, checked at runtime.
 *
 * For names that only exist as strings at runtime — read from a database, a form, or a user —
 * where {@link exercise}'s compile-time check cannot reach. A `false` here is the upload that
 * would otherwise have stored an empty `exerciseName`.
 */
export function isExerciseName(category: string, name: string): boolean {
  // `Object.hasOwn`, not a bare index: `isExerciseName("constructor", ...)` would otherwise reach
  // `Object.prototype.constructor` and throw on `.includes`, and `"toString"` would be reported
  // as a valid exercise for every category.
  if (!Object.hasOwn(EXERCISES, category)) return false;
  const names = (EXERCISES as Record<string, readonly string[]>)[category]!;
  return names.includes(name);
}
