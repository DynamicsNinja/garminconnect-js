/**
 * Garmin's exercise catalogue: every 1830 exercise names Garmin accepts, grouped by the
 * 51 categories that have any.
 *
 * Published as a SEPARATE entry point — `garminconnect-js/exercises` — because it is roughly a
 * third of the package's size and most callers never need it. Importing the package root does not
 * pull it in.
 *
 * Why it exists: Garmin validates the two halves of an exercise differently. A bad `category`
 * fails the whole upload with a 400 — loud. A bad `exerciseName` is accepted and SILENTLY STORED
 * AS `""`, leaving a step with a category and no exercise and no error anywhere. This module makes
 * that failure a compile error instead:
 *
 * ```ts
 * import { buildWorkout } from "garminconnect-js";
 * import { exercise } from "garminconnect-js/exercises";
 *
 * buildWorkout("Legs", { sport: "strength_training" })
 *   .interval({ reps: 8, exercise: exercise("SQUAT", "BARBELL_BACK_SQUAT") })
 *   .interval({ reps: 8, exercise: exercise("SQUAT", "BARBELL_BENCH_PRESS") }) // compile error
 *   .build();
 * ```
 *
 * PROVENANCE — every pair here was confirmed by the server, not assumed. Candidates came from
 * Garmin Connect's own translations bundle
 * (https://connect.garmin.com/web-translations/exercise_types/exercise_types.properties, public,
 * no auth), and `scripts/verify-exercises.ts` then uploaded each one to a live account, read the
 * stored workout back, and kept only the names Garmin echoed unchanged. 44 candidates were
 * rejected that way — mostly the translation file's per-category generic label
 * (`SQUAT_SQUAT` and friends), which is not an exercise.
 *
 * Two further categories, `STRETCH` and `UNKNOWN`, are valid on the wire but have no exercise
 * names in Garmin's catalogue, so they do not appear here. Pass them as a bare
 * `{ category }` with no `name`. The full category list is `WORKOUT_EXERCISE_CATEGORIES` in the
 * package root.
 *
 * This file is generated. To regenerate, see `scripts/verify-exercises.ts`.
 */
